import type { EvalCase } from "./types.js"

export const CORPUS_VERSION = 1

type Scenario = {
  id: string
  title: string
  initial: string
  progress: string
  request: string
  path: string
  command: string
  error: string
  constraint: string
  next: string
  unsupported: [string, string]
}

function scenario(input: Scenario): EvalCase {
  const facts = [input.path, input.command, input.error, input.constraint]
  return {
    id: input.id,
    title: input.title,
    messages: [
      { role: "user", text: input.initial },
      {
        role: "assistant",
        text: input.progress,
        tool: {
          name: "workspace-check",
          status: input.error === "no error recorded" ? "completed" : "error",
          title: `Inspect ${input.path}`,
          input: { path: input.path, command: input.command },
          ...(input.error === "no error recorded"
            ? { output: `Verified the bounded fixture at ${input.path}.` }
            : { error: input.error }),
        },
      },
      {
        role: "user",
        text: `${input.request} Keep these exact recovery facts: ${facts.join("; ")}. Do not claim work that was not verified.`,
      },
    ],
    todos: [
      { id: `${input.id}-done`, content: input.progress, status: "completed", priority: "medium" },
      { id: `${input.id}-next`, content: input.next, status: "pending", priority: "high" },
    ],
    key_facts: facts.map((value, index) => ({ id: `${input.id}-fact-${index + 1}`, value })),
    unsupported_claims: input.unsupported,
  }
}

